def js_str(s):
    return '"' + "".join("\\u%04x" % ord(ch) for ch in s) + '"'


def dump(name, mapping):
    lines = [f"export const {name} = {{"]
    for key, val in mapping.items():
        lines.append(f"  {key}: {js_str(val)},")
    lines.append("}")
    return "\n".join(lines) + "\n"


